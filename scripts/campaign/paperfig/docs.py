"""docs/paper/FIGURES.md and the preview document's figure list, both from
the registry (evaluation figures) and docs/diagrams/tikz/diagrams.json
(design diagrams), so every caption is written once."""
import json
import os
import re
import subprocess

from .data import ROOT

PAPER = os.path.join(ROOT, "docs", "paper")
DIAGRAMS = os.path.join(ROOT, "docs", "diagrams", "tikz", "diagrams.json")

SECTIONS = ["System Design", "System Design > Placement", "System Design > Environment Reproduction",
            "System Design > Joining Across Networks", "System Design > Transparent Interception",
            "System Design > The Cost Model", "System Design > Degradation Guarantee and Operation",
            "System Design > Implementation", "Evaluation", "Evaluation > Setup",
            "Evaluation > Microbenchmarks (Q1, Q2)", "Evaluation > End-to-end runs (Q3)",
            "Evaluation > Training (Q4)"]


def section_key(s):
    return SECTIONS.index(s) if s in SECTIONS else len(SECTIONS)


def tex(s):
    s = s.replace("\\", r"\textbackslash{}")
    for c in "&%$#_{}":
        s = s.replace(c, "\\" + c)
    s = s.replace("~", r"\textasciitilde{}").replace("×", r"$\times$")
    return re.sub(r"(?<=\s)-(?=\s)", "--", s)


def entries(figs, sizes):
    """Every figure as {name, kind, file, preview, width, size, section, shows, caption}."""
    out = []
    if os.path.exists(DIAGRAMS):
        for d in json.load(open(DIAGRAMS)):
            pdf = os.path.join(ROOT, d["file"])
            out.append({"name": d["name"], "kind": "diagram", "file": d["file"],
                        "preview": os.path.relpath(pdf, PAPER), "width": d["width"], "size": pdf_size(pdf),
                        "section": d["section"], "shows": d["shows"], "caption": d["caption"]})
    for f in figs:
        out.append({"name": f.name, "kind": "evaluation", "file": "docs/paper/figures/%s.pdf" % f.name,
                    "preview": "figures-draft/%s.pdf" % f.name, "width": f.width,
                    "size": sizes.get(f.name) or pdf_size(os.path.join(PAPER, "figures-draft", f.name + ".pdf")),
                    "section": f.section, "shows": f.shows, "caption": f.caption, "order": f.order})
    out.sort(key=lambda e: (section_key(e["section"]), e["kind"] != "diagram", e.get("order", 0)))
    return out


def pdf_size(path):
    """(w, h) in inches of the PDF's first page (pdfinfo), or None."""
    if not os.path.exists(path):
        return None
    try:
        out = subprocess.run(["pdfinfo", path], capture_output=True, text=True, check=True).stdout
    except (OSError, subprocess.CalledProcessError):
        return None
    m = re.search(r"Page size:\s+([\d.]+) x ([\d.]+) pts", out)
    return (round(float(m.group(1)) / 72, 2), round(float(m.group(2)) / 72, 2)) if m else None


def label(e):
    return "fig:" + e["name"]


def preview_body(es, skipped):
    out = ["% Generated by scripts/campaign/paper_figures.py --docs; do not edit.", "",
           "\\section*{Figures}", "{\\footnotesize\\begin{itemize}\\setlength{\\itemsep}{0pt}"]
    sec = None
    for e in es:
        if e["section"] != sec:
            sec = e["section"]
            out.append("\\item[] \\textit{%s}" % tex(sec.replace(" > ", ": ")))
        state = " (skipped)" if e["name"] in skipped else ""
        out.append("\\item Fig.~\\ref{%s}: \\texttt{%s}, %s%s" % (label(e), tex(e["name"]), e["width"], state))
    out += ["\\end{itemize}}", ""]
    for e in es:
        if e["name"] in skipped:
            out.append("\\noindent\\textbf{%s} skipped: %s.\\par" % (tex(e["name"]), tex(skipped[e["name"]])))
            continue
        double = e["width"] == "double"
        size = "%.2f$\\times$%.2f\\,in" % tuple(e["size"]) if e["size"] else "size unknown"
        tag = "\\par\\vspace{2pt}{\\color{black!55}\\scriptsize\\texttt{%s}: %s column, %s, %s}" % (
            tex(e["name"]), e["width"], size, tex(e["section"].replace(" > ", ": ")))
        out += ["\\begin{%s}[%s]" % ("figure*" if double else "figure", "!t" if double else "!htb"), "\\centering",
                "\\includegraphics{%s}" % e["preview"], tag,
                "\\caption{%s}" % tex(e["caption"]), "\\label{%s}" % label(e),
                "\\end{%s}" % ("figure*" if double else "figure"), ""]
    return "\n".join(out) + "\n"


def figures_md(es, skipped):
    out = ["# Paper figures", "",
           "Every figure for `docs/paper/paper.tex`, at its final size: single column 252 pt (3.49 in), "
           "double column 516 pt (7.14 in, `figure*`), which are IEEEtran's own `\\columnwidth` and "
           "`\\textwidth` (IEEE's nominal 3.5 in and 7.16 in overflow the class by 1-1.5 pt). Include them at their natural size (`\\includegraphics{...}` with no "
           "width) so nothing is scaled and the 8 pt labels stay 8 pt.", "",
           "- Evaluation figures: `scripts/campaign/paper_figures.py` writes `docs/paper/figures/<name>.pdf` "
           "(and a 600 dpi PNG) from `results/lab/` (the lab day). `--sample` draws the container sample; "
           "`--draft` writes `docs/paper/figures-draft/` with an \"emulated\" stamp, for the preview only.",
           "- Design diagrams: TikZ sources in `docs/diagrams/tikz/`, built by `docs/diagrams/tikz/build.sh` "
           "into `docs/diagrams/tikz/pdf/`.",
           "- Preview: `docs/paper/build-preview.sh` regenerates everything and compiles "
           "`docs/paper/figures-preview.pdf` (IEEEtran, every figure at its real size with its draft caption); "
           "page renders in `docs/paper/preview-pages/`.",
           "- Style: `scripts/campaign/paperfig/style.py` and `paper.mplstyle` (plots), "
           "`docs/diagrams/tikz/ppstyle.tex` (diagrams). One mapping everywhere: PipedPeer blue #0072B2, "
           "solid, circle; Ray vermilion #D55E00, dashed, square, `////`; Dask green #009E73, dash-dot, "
           "triangle, `\\\\`; plain Python grey #595959, dotted, diamond; torchrun purple #CC79A7, "
           "triangle down, `xx`.", "",
           "After the lab day: `python3 scripts/campaign/paper_figures.py` reads `results/lab/` (runs.jsonl, "
           "otel/, logs/, timeline.jsonl, energy/, node-ids.csv) and writes the final figures to "
           "`docs/paper/figures/`, unstamped; `docs/paper/build-preview.sh --lab` rebuilds the preview from "
           "them. A figure whose data is missing is listed in `skipped.txt` with the reason. To check layouts "
           "at lab scale first, `python3 scripts/campaign/paperfig/synth.py DIR` writes an invented 17-PC "
           "results directory (outside the repository; never for the paper).", "",
           "This file and the preview's figure list are generated (`paper_figures.py --docs`); edit captions "
           "in `scripts/campaign/paperfig/figs_*.py` or `docs/diagrams/tikz/diagrams.json`.", ""]
    sec = None
    for e in es:
        if e["section"] != sec:
            sec = e["section"]
            out += ["## %s" % sec, "", "| Figure | File | Width | Size (in) | Shows | Suggested caption |",
                    "|---|---|---|---|---|---|"]
        size = "%.2f x %.2f" % tuple(e["size"]) if e["size"] else "-"
        note = " (skipped on the sample: %s)" % skipped[e["name"]] if e["name"] in skipped else ""
        out.append("| `%s` | `%s` | %s | %s | %s%s | %s |" % (
            e["name"], e["file"], e["width"], size, e["shows"].replace("|", "/"), note,
            e["caption"].replace("|", "/")))
        nxt = es.index(e) + 1
        if nxt == len(es) or es[nxt]["section"] != sec:
            out.append("")
    return "\n".join(out) + "\n"


def write(figs, sizes, skipped):
    es = entries(figs, sizes)
    open(os.path.join(PAPER, "figures-preview-body.tex"), "w").write(preview_body(es, skipped))
    open(os.path.join(PAPER, "FIGURES.md"), "w").write(figures_md(es, skipped))
    return es
