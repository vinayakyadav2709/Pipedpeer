"""E19: cold vs warm ship, time to first result while a user iterates on a
script. At N=16 (rehearsal: 2), pipedpeer and ray, in a random order, four
runs each, in this order:

  cold    a script never run on this cluster: a Pool.map over networkx
          graphs (networkx is in no other experiment, so its environment
          is new: pipedpeer builds a closure on pc00 and ships it to every
          peer that takes work; Ray pip-installs it on every node)
  warm    the same script again, unchanged
  edit    one constant changed in the script, no new dependency (a new
          workspace, the same environment)
  newdep  the edited script with one more import, rich, used by the work
          function: a new environment again

The scripts are generated here from one template, written to
results/lab/e19/<phase>/ and staged into one workspace per system, file
e19_ship.py, overwritten in place as a user's edit would be. Ray's port
(e19_ship_ray.py) runs the same function under ray.util.multiprocessing
.Pool with runtime_env={"working_dir": ".", "pip": [...]}; its imports
move into the function, since the driver's python (the campaign env) has
neither package. ttfr_s is the wall from typing the command to the result
printed (the script prints only at the end, and its work is small, so the
wall is the time to first result). pipedpeer lines add env_build_s,
env_send_s and script_s from the run's step record.

Dask is not run: it has no per-job environment. Its PipInstall plugin
pip-installs into every worker (and restarts them for a new package),
which E5's pip method already measures.
"""
import hashlib
import json
import os

from campaign.workloads import Workload

SYSTEMS = ["pipedpeer", "ray"]
PHASES = [("cold", 0, False), ("warm", 0, False), ("edit", 1, False), ("newdep", 1, True)]

TEMPLATE = '''"""E19 (generated by scripts/campaign/experiments/e19.py): Pool.map over
random graphs. Phase %(phase)s."""
import os
import time
from multiprocessing import Pool
%(imports)s
SEED_OFFSET = %(offset)d


def work(i):
%(lazy)s    g = nx.gnm_random_graph(120, 600, seed=i + SEED_OFFSET)
    v = sum(nx.triangles(g).values()) // 3 + nx.number_connected_components(g)
%(use)s    return v


if __name__ == "__main__":
    n = int(os.environ.get("E19_ITEMS", "400"))
    t0 = time.perf_counter()
%(init)s    with Pool(int(os.environ.get("BENCH_PROCS", "8"))) as p:
        out = p.map(work, range(n))
    print("E19 items=%%d total=%%d" %% (n, sum(out)))
    print("seconds=%%.3f" %% (time.perf_counter() - t0))
'''

USE_RICH = "    v += len(Text(str(v)).plain) * 0\n"


def source(phase, offset, rich, ray):
    pips = ["networkx"] + (["rich"] if rich else [])
    if ray:
        imports = "\nimport ray\nfrom ray.util.multiprocessing import Pool  # noqa: F811\n"
        lazy = "    import networkx as nx\n" + ("    from rich.text import Text\n" if rich else "")
        init = ('    ray.init(address=os.environ.get("RAY_ADDRESS", "auto"),\n'
                '             runtime_env={"working_dir": ".", "pip": %r})\n' % pips)
    else:
        imports = "\nimport networkx as nx\n" + ("from rich.text import Text\n" if rich else "")
        lazy = init = ""
    return TEMPLATE % {"phase": phase, "imports": imports, "offset": offset, "lazy": lazy,
                       "use": USE_RICH if rich else "", "init": init}


def write_scripts(ctx):
    """{phase: Workload}, the files under results/lab/e19/<phase>/."""
    out = {}
    for phase, offset, rich in PHASES:
        d = os.path.join(ctx.out_dir, "e19", phase)
        os.makedirs(d, exist_ok=True)
        for name, ray in (("e19_ship.py", False), ("e19_ship_ray.py", True)):
            with open(os.path.join(d, name), "w") as f:
                f.write(source(phase, offset, rich, ray))
        out[phase] = Workload({
            "id": "E19", "script": os.path.join(d, "e19_ship.py"),
            "ports": {"ray": os.path.join(d, "e19_ship_ray.py")},
            "strong": {"E19_ITEMS": "2000"}, "smoke": {"E19_ITEMS": "400"},
            "system_env": {"pipedpeer": {"BENCH_PROCS": "{nproc_submitter}"},
                           "ray": {"BENCH_PROCS": "{nproc_workers}"}},
            "result_regex": r"items=\d+|total=\d+", "result_compare": "equal",
            "timing_regex": r"seconds=([0-9.]+)"})
    return out


def src_hash(wl):
    with open(wl.script, "rb") as f:
        return hashlib.sha1(f.read()).hexdigest()[:10]


def steps(path):
    """env_build_s, env_send_s, script_s from `pipedpeer jobs last --export json`."""
    try:
        with open(path) as f:
            rec = json.load(f)
    except (OSError, ValueError, TypeError):
        return {}
    out = {}
    for s in rec.get("steps") or []:
        k = {"env_build": "env_build_s", "env_send": "env_send_s", "script": "script_step_s"}.get(s.get("step"))
        if k:
            out[k] = round(out.get(k, 0) + (s.get("dur_ns") or 0) / 1e9, 3)
    sent = sum(s.get("bytes") or 0 for s in rec.get("steps") or [] if s.get("step") == "env_send")
    if sent:
        out["env_send_bytes"] = sent
    return out


def forget_stage(staged, wl_id, system):
    """ctx._staged without the system's E19 workspace, so the next run
    stages the phase's script over the last one: the user's edit."""
    return {k for k in staged if not k[1].endswith("/work/%s-%s" % (wl_id, system))}


def one(ctx, wl, system, n, phase):
    ctx._staged = forget_stage(ctx._staged, wl.id, system)

    def run(b, wl_, env, logdir, n_):
        res = b.run(wl_, env, logdir, n_)
        res["ttfr_s"] = round((res["end_ns"] - res["start_ns"]) / 1e9, 3) if res.get("end_ns") else None
        if b.kind == "pipedpeer" and res.get("record_path"):
            res.update(steps(res["record_path"]))
        return res

    ctx.one_run(wl, system, n, 1, reference="first", run=run, extra={"phase": phase, "variant": phase})


def main(ctx):
    n = ctx.ns([16])[-1]
    wls = write_scripts(ctx)
    chosen = [s for s in SYSTEMS if ctx.enabled(s)]
    for system in ctx.rng.sample(chosen, len(chosen)):
        for phase, _, _ in PHASES:
            wl = wls[phase]
            # The result cache is keyed by size: keep the phases apart, and
            # key by the script's text too, so an edited template never meets
            # an old reference.
            key = {"E19_PHASE": phase, "E19_SRC": src_hash(wl)}
            wl.strong = dict(wl.strong, **key)
            wl.smoke = dict(wl.smoke, **key)
            one(ctx, wl, system, n, phase)
